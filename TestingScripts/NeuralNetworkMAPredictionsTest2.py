# The function calculates the expectation value of the cost Hamiltonian for Multi-Angle
# QAOA and uses a tool found in this GitHub repository:
# https://github.com/GaidaiIgor/MA-QAOA/tree/main/src
def optimizerfunction(thetas,optimizer):
    val = -optimizer.func(thetas)
    global optimization_history_storage
    optimization_history_storage.append(val)
    return val

# %%
# Create a function that constructs the cicuit that implements Multi-Angle QAOA
# using Qiskit so that the width and depth of the relevant quantum algorith for 
# assessing the total amount of resources used.
def MAQAOA_Max_Cut_QC(thetas,edges,nqubits,pval):
    qc = QuantumCircuit(nqubits)
    for i in range(nqubits):
        qc.h(i)
    # The variable count is used to index the appropriate angle used for the
    # phase separator and mixer.
    count = 0
    for i in range(pval):
        for j in range(len(edges)):
            qc.rzz(-2*thetas[count],round(edges[j][0]),round(edges[j][1]))
            count = count + 1
        for j in range(nqubits):
            qc.rx(-2*thetas[count],j)
            count = count + 1
    return qc

